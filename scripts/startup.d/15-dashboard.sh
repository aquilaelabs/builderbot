#!/usr/bin/env bash
#
# Web dashboard: the page, its API and the browser terminals, all on
# DASHBOARD_PORT. ttyd binds the loopback and is reached through the
# dashboard's own /term proxy, so there is one port and one sign-in.
#
# Numbered 15 so it starts BEFORE the slow hooks rather than after them. It
# needs nothing they produce — ttyd, tmux and python are in the image — and it
# used to run second-to-last, which meant the whole boot was time the operator
# spent looking at a browser that would not connect. Measured on this box: a
# container start to the runner listening is about fifty seconds, and the
# Claude Code update at hook 20 and any project's own setup.sh at hook 40 are
# both ahead of where this used to sit.
#
# What that costs is a few seconds of a dashboard that does not know everything
# yet: the SDK share is listed as a project until hook 41 marks it, git columns
# are blank until 30, and Claude's version is unknown until 20. Every one of
# those is a poll away from correcting itself, and none of them is worth the
# whole page for.
#
# 61-sessions.sh restores saved terminals into this one's tmux and deliberately
# does NOT move with it: a restored Claude session starting before hook 30 has
# no ssh agent yet, so its first push would fail for a reason that has nothing
# to do with the session. The dashboard being up early costs nothing; sessions
# being up early costs that.
#
# Off unless ENABLE_DASHBOARD is true, and it refuses to start without
# DASHBOARD_AUTH. That refusal is the point: this serves an interactive shell
# into a container holding a loaded ssh-agent and read-write mounts of every
# project, so an unauthenticated instance on a LAN would hand all of that to
# anyone who can reach the port. Failing loudly beats defaulting to open.
#
set -euo pipefail
. /opt/builderbot/scripts/lib/common.sh

is_true "${ENABLE_DASHBOARD:-false}" || exit 0

PORT="${DASHBOARD_PORT:-7680}"
TTYD_PORT="${DASHBOARD_TTYD_PORT:-7681}"
DASH=/opt/builderbot/scripts/dashboard

if [ -z "${DASHBOARD_AUTH:-}" ]; then
    warn "ENABLE_DASHBOARD=true but DASHBOARD_AUTH is empty — dashboard NOT started."
    warn "Set DASHBOARD_AUTH=user:password. It exposes a shell with your ssh keys"
    warn "and every mounted project; it will not run without a credential."
    exit 0
fi
case "$DASHBOARD_AUTH" in
    *:*) ;;
    *) warn "DASHBOARD_AUTH must be user:password — dashboard NOT started."; exit 0 ;;
esac

for bin in ttyd tmux; do
    command -v "$bin" >/dev/null 2>&1 \
        || { warn "${bin} is missing from this image — dashboard NOT started."; exit 0; }
done

# tmux keeps sessions alive across browser disconnects, which is the only
# reason a closed tab does not kill a Claude session mid-turn.
#
# Our settings live in their own file, which we own and overwrite; ~/.tmux.conf
# merely sources it, and is created only if absent. The home directory is a
# persistent volume, so writing ~/.tmux.conf directly meant reverting the
# user's own tmux config on every container start.
cat > "$HOME/.tmux.builderbot.conf" <<'EOF'
# Generated by BuilderBot on every start. Edit ~/.tmux.conf instead — anything
# you put there after the source-file line wins.
set -g history-limit 50000

# Mouse mode decides who owns a drag, and the answer differs per session. With
# it ON, tmux takes the drag: the text lands in a tmux paste buffer and the
# browser never sees a selection, so nothing reaches the system clipboard. With
# it OFF, the terminal makes an ordinary browser selection and copies it as you
# release the button.
#
# Shells want the clipboard, Claude's interface wants the mouse, so bb-tty sets
# this per session as it launches one — that is the authoritative copy, and it
# holds even where this file is not read. This is the default for a session
# started any other way.
#
# The cost in a shell is that the wheel no longer scrolls tmux's scrollback —
# at a prompt it walks shell history instead. `Ctrl-b [` enters copy mode,
# where the wheel scrolls again. Put `set -g mouse on` in ~/.tmux.conf after
# the source-file line to have the old behavior back everywhere.
set -g mouse off

# PgUp at a prompt scrolls back: it enters copy mode a page up, PgDn pages
# forward, and copy mode ends by itself the moment you are back at the bottom
# (-e), so there is no mode to remember. Inside a full-screen program (less,
# vim) the key stays the program's. This is also how a phone scrolls: a
# finger drag reaches nothing in the browser terminal (tmux holds the
# alternate screen and xterm.js only turns WHEEL events into anything tmux
# sees), and the dashboard's on-screen PgUp/PgDn make the same decision
# server-side, since send-keys bypasses this table.
bind -n PPage if-shell -F '#{alternate_on}' 'send-keys PPage' 'copy-mode -eu'

# tmux's right-click menu is drawn in the terminal, underneath the browser's
# context menu, which covers it. The browser's cannot be suppressed from
# outside the frame, so the one we control is the one that goes.
unbind -n MouseDown3Pane
unbind -n MouseDown3Status
unbind -n MouseDown3StatusLeft
unbind -n MouseDown3StatusRight
set -g status-style bg=colour236,fg=colour252
set -g status-left '#[bold] #S '
set -g status-right ' builderbot '
setw -g aggressive-resize on
EOF

if [ ! -e "$HOME/.tmux.conf" ]; then
    printf 'source-file ~/.tmux.builderbot.conf\n' > "$HOME/.tmux.conf"
elif ! grep -qF 'tmux.builderbot.conf' "$HOME/.tmux.conf"; then
    # An image before this one wrote its settings straight into ~/.tmux.conf.
    # On a persistent home that copy is still there, still saying `mouse on`,
    # and it never sources the file we own now — so an upgraded install would
    # keep the old behavior forever and no message about it would explain why.
    # Recognize our own leftovers by their status line and replace them, keeping
    # a copy. Anything we do not recognize is the operator's and is left alone.
    if grep -qF "status-right ' builderbot '" "$HOME/.tmux.conf"; then
        mv -f "$HOME/.tmux.conf" "$HOME/.tmux.conf.builderbot-old"
        printf 'source-file ~/.tmux.builderbot.conf\n' > "$HOME/.tmux.conf"
        log "dashboard: replaced an older BuilderBot ~/.tmux.conf with a source-file line (old copy kept as ~/.tmux.conf.builderbot-old)"
    else
        log "dashboard: keeping your ~/.tmux.conf — add 'source-file ~/.tmux.builderbot.conf' to it for the defaults"
    fi
fi

# One port to publish: terminals are proxied under /term on this one.
log "dashboard: http://<host>:${PORT}  (terminals proxied at /term; ttyd binds 127.0.0.1:${TTYD_PORT})"

# --url-arg lets the page choose the session; bb-tty validates it. -W makes
# the terminal writable, which is the entire point. `-t reconnect=5` shortens
# ttyd's own auto-reconnect after a dropped socket from its 10s default — it
# heals a desktop blip on its own. It does NOT cover a phone, whose browser
# freezes the page's timers while it is backgrounded so the reconnect never
# fires; the dashboard reloads the terminal iframe on return for that
# (reattaching tmux, losslessly).
#
# Loopback only, and no --credential: the browser reaches terminals through
# the dashboard's /term proxy on the dashboard's own port, which enforces the
# one sign-in for everything. Nothing else can reach this port from outside
# the container, and binding wider would only re-create the second
# credentials prompt this arrangement exists to remove.
nohup ttyd --port "$TTYD_PORT" --interface 127.0.0.1 \
        --url-arg --writable \
        --max-clients 16 \
        -t reconnect=5 \
        "$DASH/bb-tty" \
    >> "$(bb_log_dir)/ttyd.log" 2>&1 &

nohup env DASHBOARD_PORT="$PORT" DASHBOARD_TTYD_PORT="$TTYD_PORT" \
        DASHBOARD_AUTH="$DASHBOARD_AUTH" \
        python3 "$DASH/server.py" \
    >> "$(bb_log_dir)/dashboard.log" 2>&1 &

# Neither is supervised: a dashboard that dies should not take the workstation
# with it, and the container is useful without it. `bb logs` names the files.
